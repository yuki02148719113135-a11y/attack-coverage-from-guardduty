#!/usr/bin/env python3
"""Fetch actually-observed GuardDuty finding types and write a --covered file.

自分の AWS 環境で実際に出た GuardDuty finding type を集計して、
generate_layer.py の --covered に渡せる形（1 行 1 finding type）で出力する。

前提:
    pip install boto3
    AWS 認証情報が設定済み（aws configure / 環境変数 / SSO など）
    対象アカウントで GuardDuty が有効化されていること

使い方:
    python src/fetch_covered.py --region ap-northeast-1
    python src/fetch_covered.py --all-regions --days 30
    python src/generate_layer.py --covered output/covered.txt --name "Real coverage"
"""
from __future__ import annotations

import argparse
import sys
import time
from collections import Counter
from pathlib import Path

try:
    import boto3
except ImportError:
    sys.exit("boto3 が必要です:  pip install boto3")


def finding_types_in_region(session, region, days):
    gd = session.client("guardduty", region_name=region)
    counts = Counter()

    detector_ids = gd.list_detectors().get("DetectorIds", [])
    if not detector_ids:
        return counts

    criteria = None
    if days:
        since_ms = int((time.time() - days * 86400) * 1000)
        criteria = {"Criterion": {"updatedAt": {"GreaterThanOrEqual": [str(since_ms)]}}}

    for det in detector_ids:
        finding_ids = []
        paginator = gd.get_paginator("list_findings")
        kwargs = {"DetectorId": det}
        if criteria:
            kwargs["FindingCriteria"] = criteria
        for page in paginator.paginate(**kwargs):
            finding_ids.extend(page.get("FindingIds", []))

        for i in range(0, len(finding_ids), 50):
            chunk = finding_ids[i : i + 50]
            resp = gd.get_findings(DetectorId=det, FindingIds=chunk)
            for f in resp.get("Findings", []):
                counts[f["Type"]] += 1

    return counts


def load_mapped_types(mapping_path):
    try:
        import yaml
    except ImportError:
        return None
    try:
        data = yaml.safe_load(Path(mapping_path).read_text(encoding="utf-8"))
        return {f["finding_type"] for f in data["findings"]}
    except Exception:
        return None


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--region", help="対象リージョン（例: ap-northeast-1）")
    ap.add_argument("--all-regions", action="store_true", help="GuardDuty 対応の全リージョンを走査")
    ap.add_argument("--days", type=int, help="直近 N 日に更新された finding だけに絞る")
    ap.add_argument("--profile", help="使う AWS プロファイル名")
    ap.add_argument("--out", default="output/covered.txt", help="出力先（--covered に渡すファイル）")
    ap.add_argument("--mapping", default="mappings/guardduty_attack_mapping.yaml",
                    help="未マッピングの finding type を照合する元ファイル")
    args = ap.parse_args()

    session = boto3.Session(profile_name=args.profile) if args.profile else boto3.Session()

    if args.all_regions:
        regions = session.get_available_regions("guardduty")
    elif args.region:
        regions = [args.region]
    else:
        region = session.region_name
        if not region:
            sys.exit("リージョンが決まりません。--region か --all-regions を指定してください。")
        regions = [region]

    total = Counter()
    for region in regions:
        try:
            counts = finding_types_in_region(session, region, args.days)
        except Exception as e:
            print(f"  [skip] {region}: {e}", file=sys.stderr)
            continue
        if counts:
            print(f"  {region}: {sum(counts.values())} findings / {len(counts)} types")
        total.update(counts)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# auto-generated by fetch_covered.py — observed GuardDuty finding types"]
    for ftype, n in sorted(total.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"{ftype}  # x{n}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"\nWrote {out}")
    print(f"  observed finding types : {len(total)}")
    print(f"  total findings         : {sum(total.values())}")

    mapped = load_mapped_types(args.mapping)
    if mapped is not None:
        unmapped = sorted(set(total) - mapped)
        if unmapped:
            print(f"\n  mapping 未登録の finding type（{len(unmapped)} 件）— YAML に足す候補:")
            for ft in unmapped:
                print(f"    {ft}")
        else:
            print("\n  観測された finding type はすべて mapping 済み。")


if __name__ == "__main__":
    main()
